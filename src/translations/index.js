/**
 * Gets a nested value from an object by dot-path string.
 * e.g. get(obj, 'nav.home') → obj.nav.home
 */
function get(obj, path) {
  return path.split('.').reduce((o, k) => (o && o[k] !== undefined ? o[k] : undefined), obj);
}

/**
 * Returns the translation for a given key path in a given locale.
 * Falls back to the English value, then the key itself.
 */
export function t(locale, keyPath, fallback) {
  const val = get(translations[locale], keyPath);
  if (val !== undefined) return val;
  const enVal = get(translations.en, keyPath);
  return enVal ?? fallback ?? keyPath;
}
